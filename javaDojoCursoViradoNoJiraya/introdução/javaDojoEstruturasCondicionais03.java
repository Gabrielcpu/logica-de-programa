public class javaDojoEstruturasCondicionais03 {
    public static void main(String[] args) {
        // doar se salario > 5000
        double salario = 6000;
        //(condição) ? verdadeiro : falso

        System.out.println( salario > 5000 ? "vou doar 500 pro dojo" : "não vou poder doar 500" );
    }
}
